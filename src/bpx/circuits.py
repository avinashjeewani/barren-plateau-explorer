"""Circuits, cost functions and initialization strategies.

Ansatz (hardware-efficient):
    each layer = RY and RZ on every qubit, then a CZ ladder (0-1, 1-2, ...).
    Parameters have shape (layers, n_qubits, 2).

Input state: every circuit starts from |+>^n (a Hadamard on each qubit). This matters for
identity-block init: if the input were |0...0>, an identity circuit would already sit at the
cost's global minimum and every gradient would be exactly zero.

Cost functions (both measure distance from |0...0> and lie in [0, 1]):
    global: C = 1 - P(all qubits measure 0)
    local:  C = 1 - (1/n) * sum_i P(qubit i measures 0) = 1/2 - (1/2n) sum_i <Z_i>

Initialization strategies:
    uniform        every angle ~ U(0, 2*pi)                       (the standard "random" init)
    small_angle    every angle ~ N(0, sigma^2), sigma = 0.1         (starts near the identity)
    identity_block first half of the layers random, second half is its exact inverse,
                   so the whole circuit is the identity at initialization (Grant et al., 2019)
"""
from __future__ import annotations

import numpy as np
import pennylane as qml

COSTS = ("global", "local")
INITS = ("uniform", "small_angle", "identity_block")


def _layer(params_l, n_qubits):
    """One ansatz layer. params_l has shape (batch, n_qubits, 2) or (n_qubits, 2)."""
    for q in range(n_qubits):
        qml.RY(params_l[..., q, 0], wires=q)
        qml.RZ(params_l[..., q, 1], wires=q)
    for q in range(n_qubits - 1):
        qml.CZ(wires=[q, q + 1])


def ansatz(params, n_qubits, identity_block=False):
    """Apply all layers. With identity_block=True, the second half undoes the first."""
    n_layers = params.shape[-3]
    if not identity_block:
        for l in range(n_layers):
            _layer(params[..., l, :, :], n_qubits)
        return
    half = n_layers // 2
    for l in range(half):
        _layer(params[..., l, :, :], n_qubits)
    for l in range(half):
        # Inverse of layer (half - 1 - l), using its own copy of the parameters
        # stored in slot half + l, so every parameter is still trainable.
        qml.adjoint(_layer)(params[..., half + l, :, :], n_qubits)


def prepare_input(n_qubits):
    for q in range(n_qubits):
        qml.Hadamard(wires=q)


def make_cost(n_qubits: int, cost: str, identity_block: bool = False):
    """Return a batched cost function C(params) -> array of shape (batch,)."""
    if cost not in COSTS:
        raise ValueError(f"cost must be one of {COSTS}")
    dev = qml.device("default.qubit", wires=n_qubits)

    if cost == "global":

        @qml.qnode(dev)
        def circuit(params):
            prepare_input(n_qubits)
            ansatz(params, n_qubits, identity_block)
            return qml.probs(wires=range(n_qubits))

        def C(params):
            return 1.0 - np.asarray(circuit(params))[..., 0]

    else:

        @qml.qnode(dev)
        def circuit(params):
            prepare_input(n_qubits)
            ansatz(params, n_qubits, identity_block)
            return [qml.expval(qml.PauliZ(q)) for q in range(n_qubits)]

        def C(params):
            z = np.stack([np.asarray(v) for v in circuit(params)], axis=-1)
            return 0.5 - z.mean(axis=-1) / 2.0

    return C


def sample_params(rng, n_samples, n_layers, n_qubits, init: str, sigma: float = 0.1):
    """Draw a batch of initial parameters, shape (n_samples, n_layers, n_qubits, 2)."""
    shape = (n_samples, n_layers, n_qubits, 2)
    if init == "uniform":
        return rng.uniform(0, 2 * np.pi, size=shape)
    if init == "small_angle":
        return rng.normal(0.0, sigma, size=shape)
    if init == "identity_block":
        if n_layers % 2:
            raise ValueError("identity_block init needs an even number of layers")
        p = rng.uniform(0, 2 * np.pi, size=shape)
        half = n_layers // 2
        # Slot half + l holds the parameters of layer half - 1 - l, applied inverted.
        p[:, half:] = p[:, :half][:, ::-1]
        return p
    raise ValueError(f"init must be one of {INITS}")


def gradient_first_param(C, params):
    """Exact gradient of C w.r.t. the first RY angle (layer 0, qubit 0), via parameter shift.

    Because RY is generated by a Pauli operator, dC/dtheta = [C(theta + pi/2) - C(theta - pi/2)] / 2
    exactly. Both shifted batches are evaluated in a single broadcast circuit call.
    """
    plus, minus = params.copy(), params.copy()
    plus[:, 0, 0, 0] += np.pi / 2
    minus[:, 0, 0, 0] -= np.pi / 2
    vals = C(np.concatenate([plus, minus], axis=0))
    b = len(params)
    return (vals[:b] - vals[b:]) / 2.0
