"""Turn gradients.csv into fitted decay laws (summary.md) and a three-panel chart.

For each series we fit two models to the typical gradient size G(n) = E[(dC/dtheta)^2]
over n >= fit_min_qubits, both as straight lines in log space:

    exponential:  log2 G = a + b * n         -> G shrinks by 2^b per added qubit
    polynomial:   log2 G = a + k * log2 n    -> G ~ n^k

Over a small range of n both can fit reasonably, so the verdict uses two checks:
the exponential model must fit better (higher R^2) AND the per-qubit rate must be
meaningfully negative (b < -0.3). Otherwise the decay is called polynomial (or none).
"""
from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

PALETTE = ["#5B4FCF", "#D9822B", "#2E8B57"]
TITLES = {
    "cost": "Global vs. local cost (2 layers)",
    "depth": "Circuit depth (local cost)",
    "init": "Initialization (local cost, 2n layers)",
}
METRIC = "grad_sq_mean"


def _fit(x, y):
    slope, intercept = np.polyfit(x, y, 1)
    pred = slope * x + intercept
    ss_res = ((y - pred) ** 2).sum()
    ss_tot = ((y - y.mean()) ** 2).sum()
    return slope, 1 - ss_res / ss_tot if ss_tot > 0 else 1.0


def fit_decay(sub: pd.DataFrame, fit_min: int) -> dict:
    d = sub[sub.n_qubits >= fit_min].sort_values("n_qubits")
    n = d.n_qubits.to_numpy(float)
    y = np.log2(d[METRIC].to_numpy())
    b, r2_exp = _fit(n, y)
    k, r2_pow = _fit(np.log2(n), y)
    if b < -0.3 and r2_exp >= r2_pow:
        verdict = "exponential (barren plateau)"
    elif k < -0.5:
        verdict = "polynomial"
    else:
        verdict = "none"
    return {"b": b, "k": k, "r2_exp": r2_exp, "r2_pow": r2_pow, "verdict": verdict}


def decay_table(df: pd.DataFrame, fit_min: int) -> str:
    n_lo, n_hi = df.n_qubits.min(), df.n_qubits.max()
    lines = [
        f"| Experiment | Series | E[g²] at n={n_lo} | E[g²] at n={n_hi} | Drop (×) "
        "| Exp. rate per qubit (R²) | Power law n^k (R²) | Decay |",
        "|---|---|---:|---:|---:|---:|---:|---|",
    ]
    for (exp, series), sub in df.groupby(["experiment", "series"], sort=False):
        sub = sub.sort_values("n_qubits")
        g_lo, g_hi = sub[METRIC].iloc[0], sub[METRIC].iloc[-1]
        f = fit_decay(sub, fit_min)
        lines.append(
            f"| {exp} | {series} | {g_lo:.2e} | {g_hi:.2e} | {g_lo / g_hi:,.0f} | "
            f"×{2 ** f['b']:.2f} ({f['r2_exp']:.3f}) | n^{f['k']:.1f} ({f['r2_pow']:.3f}) | {f['verdict']} |"
        )
    return "\n".join(lines)


def plot(df: pd.DataFrame, path: Path):
    exps = list(dict.fromkeys(df.experiment))
    fig, axes = plt.subplots(1, len(exps), figsize=(5.0 * len(exps), 4.3), dpi=150, sharey=True)
    axes = np.atleast_1d(axes)
    for ax, exp in zip(axes, exps):
        d = df[df.experiment == exp]
        for i, (label, sub) in enumerate(d.groupby("series", sort=False)):
            sub = sub.sort_values("n_qubits")
            yerr = [sub[METRIC] - sub.ci_low, sub.ci_high - sub[METRIC]]
            ax.errorbar(sub.n_qubits, sub[METRIC], yerr=yerr, marker="o", ms=4,
                        lw=1.6, capsize=2, color=PALETTE[i % len(PALETTE)], label=label)
        # Reference: a curve that halves with every added qubit.
        n = np.arange(d.n_qubits.min(), d.n_qubits.max() + 1)
        anchor = d[d.n_qubits == n[0]][METRIC].max()
        ax.plot(n, anchor * 2.0 ** (-(n - n[0])), ls="--", lw=1, color="#999999", label="halves per qubit (ref.)")
        ax.set_yscale("log")
        ax.set_title(TITLES.get(exp, exp), fontsize=10)
        ax.set_xlabel("Number of qubits")
        ax.set_xticks(n)
        ax.grid(alpha=0.3, which="major")
        ax.spines[["top", "right"]].set_visible(False)
        ax.legend(fontsize=7.5, frameon=False, loc="lower left")
    axes[0].set_ylabel("Typical gradient size  E[(∂C/∂θ₁)²]  (log)")
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def write_report(df: pd.DataFrame, cfg: dict, out: Path):
    fit_min = cfg.get("fit_min_qubits", 4)
    md = [
        "# Results summary",
        "",
        "_Generated by `python -m bpx.report` from `gradients.csv`. Do not edit by hand._",
        "",
        f"Each point is E[(∂C/∂θ₁)²], the mean squared gradient of the first parameter over "
        f"{int(df.n_samples.iloc[0])} initializations. Fits use n ≥ {fit_min}. "
        "\"Exp. rate per qubit\" is the factor the gradient shrinks by with each added qubit "
        "under an exponential fit; \"Power law\" is the exponent k under a fit G ∝ n^k. "
        "The decay is called exponential only if that fit is better and the rate is below ×0.81 (2^-0.3).",
        "",
        "## Gradient decay with qubit count",
        "",
        decay_table(df, fit_min),
        "",
    ]
    (out / "summary.md").write_text("\n".join(md))
    plot(df, out / "barren_plateaus.png")


if __name__ == "__main__":
    import sys

    import yaml

    out = Path(sys.argv[1] if len(sys.argv) > 1 else "results")
    cfg_path = Path(sys.argv[2] if len(sys.argv) > 2 else "configs/default.yaml")
    write_report(pd.read_csv(out / "gradients.csv"), yaml.safe_load(cfg_path.read_text()), out)
